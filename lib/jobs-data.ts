export type JobCategory = "government" | "private";

export interface BaseJob {
  id: string;
  job_hash: string;
  category: JobCategory;
  title: string;
  slug?: string;
  description: string;
  apply_url: string;
  posted_date: string;
  is_active: boolean;
  has_direct_pdf?: boolean;
  official_pdf_fallback?: string;
}

export interface GovtJob extends BaseJob {
  category: "government";
  department_or_board: string;
  gov_sector: string;
  notification_pdf_url?: string | null;
  official_pdf_fallback?: string;
  has_direct_pdf?: boolean;
  vacancies_count: number;
  last_date_to_apply: string;
  qualification: string;
  age_limit: string;
  exam_date?: string;
  fee_details?: string;
  state_or_location: string;
}

export interface PrivateJob extends BaseJob {
  category: "private";
  company_name: string;
  company_logo_url?: string;
  work_location: string;
  experience_level: string;
  employment_type: string;
  salary_range: string;
  skills_tags: string[];
  source_portal: string;
}

export type Job = GovtJob | PrivateJob;

export interface JobFilterState {
  category: "all" | "government" | "private";
  searchQuery: string;
  govBoard: string;
  state: string;
  qualification: string;
  experience: string;
  employmentType: string;
  onlyActive: boolean;
}

